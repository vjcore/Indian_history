const DEFAULT_SITE_ORIGIN = 'https://vjcore.github.io';
const MAX_BODY_BYTES = 8 * 1024 * 1024;
const SESSION_TTL_MS = 8 * 60 * 60 * 1000;

export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    const origin = request.headers.get('Origin') || '';
    const allowedOrigin = env.SITE_ORIGIN || DEFAULT_SITE_ORIGIN;
    const cors = corsHeaders(origin, allowedOrigin);

    if (request.method === 'OPTIONS') {
      if (!cors['Access-Control-Allow-Origin']) return json({ ok: false, error: 'Origin is not allowed.' }, 403, {});
      return new Response(null, { status: 204, headers: { ...cors, 'Access-Control-Max-Age': '86400' } });
    }

    if (url.pathname === '/api/health' && request.method === 'GET') {
      return json({ ok: true, service: 'Bharat Itihasa GitHub publisher', ready: Boolean(env.GH_TOKEN && env.ADMIN_PASSWORD && env.SESSION_SECRET) }, 200, cors);
    }

    if (!cors['Access-Control-Allow-Origin']) {
      return json({ ok: false, error: 'This website origin is not allowed to use the publishing backend.' }, 403, {});
    }

    if (url.pathname === '/api/login' && request.method === 'POST') {
      if (!env.ADMIN_PASSWORD || !env.SESSION_SECRET || !env.GH_TOKEN) {
        return json({ ok: false, error: 'The Worker is not fully configured. Set GH_TOKEN, ADMIN_PASSWORD and SESSION_SECRET secrets.' }, 503, cors);
      }
      const body = await readJson(request, 16_384);
      if (!body.ok) return json({ ok: false, error: body.error }, body.status, cors);
      const submitted = typeof body.data.password === 'string' ? body.data.password : '';
      if (!submitted || !constantTimeStringEqual(submitted, env.ADMIN_PASSWORD)) {
        return json({ ok: false, error: 'Incorrect backend Admin password.' }, 401, cors);
      }
      const now = Date.now();
      const claims = { sub: 'bharat-itihasa-admin', iat: now, exp: now + SESSION_TTL_MS, nonce: randomToken(18) };
      const token = await signSession(claims, env.SESSION_SECRET);
      return json({ ok: true, token, expiresAt: claims.exp, expiresInSeconds: Math.floor(SESSION_TTL_MS / 1000) }, 200, cors, { 'Cache-Control': 'no-store' });
    }

    if (url.pathname === '/api/publish' && request.method === 'POST') {
      const session = await verifySession(request.headers.get('Authorization') || '', env.SESSION_SECRET || '');
      if (!session) return json({ ok: false, error: 'Admin session expired. Sign in again.' }, 401, cors, { 'Cache-Control': 'no-store' });
      if (!env.GH_TOKEN) return json({ ok: false, error: 'GitHub token secret GH_TOKEN is missing.' }, 503, cors);

      const parsed = await readJson(request, MAX_BODY_BYTES);
      if (!parsed.ok) return json({ ok: false, error: parsed.error }, parsed.status, cors);
      const { siteSettings, overrides } = parsed.data || {};
      if (!siteSettings || typeof siteSettings !== 'object' || Array.isArray(siteSettings) || !overrides || typeof overrides !== 'object' || Array.isArray(overrides)) {
        return json({ ok: false, error: 'The Admin payload is invalid. Nothing was committed.' }, 400, cors);
      }
      // Serialize data as JSON rather than accepting arbitrary JavaScript from the browser.
      // A monotonically refreshed version lets each browser discard stale local drafts
      // once a newer site-wide publication is deployed.
      const publishVersion = Date.now();
      const content = `/* Generated by Bharat Itihasa Admin. Do not add secrets here. */\nwindow.PUBLISH_VERSION = ${publishVersion};\nwindow.SITE_SETTINGS = ${JSON.stringify(siteSettings, null, 1)};\nwindow.OVR = ${JSON.stringify(overrides, null, 1)};\n`;
      const owner = env.GH_OWNER || 'vjcore';
      const repo = env.GH_REPO || 'Indian_history';
      const branch = env.GH_BRANCH || 'main';
      const ghHeaders = {
        'Authorization': `Bearer ${env.GH_TOKEN}`,
        'Accept': 'application/vnd.github+json',
        'X-GitHub-Api-Version': '2022-11-28',
        'User-Agent': 'Bharat-Itihasa-Auto-Publisher',
        'Content-Type': 'application/json'
      };
      const githubContentsUrl = (path) => `https://api.github.com/repos/${encodeURIComponent(owner)}/${encodeURIComponent(repo)}/contents/${path}`;

      // Publish the Worker's public URL into a non-secret configuration file. This
      // happens automatically on the first successful Admin publish, so other devices
      // discover the same backend without manually configuring each browser.
      const workerUrl = new URL(request.url).origin;
      const configPath = 'data/publish-config.js';
      const configContent = `/* Public endpoint only; never place credentials here. */\nwindow.PUBLISH_API_URL = ${JSON.stringify(workerUrl)};\n`;
      const configApi = githubContentsUrl(configPath);
      const configRead = await fetch(`${configApi}?ref=${encodeURIComponent(branch)}`, { headers: ghHeaders });
      let configExisting;
      if (configRead.ok) {
        configExisting = await configRead.json();
        const currentConfig = configExisting && configExisting.content ? base64ToUtf8(configExisting.content) : '';
        if (currentConfig.trim() !== configContent.trim()) {
          const configPut = await fetch(configApi, { method: 'PUT', headers: ghHeaders, body: JSON.stringify({ message: 'Bharat Itihasa: configure public publishing endpoint', content: utf8ToBase64(configContent), branch, sha: configExisting.sha }) });
          if (!configPut.ok) { const detail = await githubError(configPut); return json({ ok: false, error: `Could not publish the public Worker URL config. ${detail}` }, 502, cors); }
        }
      } else if (configRead.status === 404) {
        const configPut = await fetch(configApi, { method: 'PUT', headers: ghHeaders, body: JSON.stringify({ message: 'Bharat Itihasa: add public publishing endpoint', content: utf8ToBase64(configContent), branch }) });
        if (!configPut.ok) { const detail = await githubError(configPut); return json({ ok: false, error: `Could not add the public Worker URL config. ${detail}` }, 502, cors); }
      } else {
        const detail = await githubError(configRead); return json({ ok: false, error: `GitHub could not read ${configPath}. ${detail}` }, 502, cors);
      }

      const path = 'data/overrides.js';
      const api = githubContentsUrl(path);
      let existing;
      const readResponse = await fetch(`${api}?ref=${encodeURIComponent(branch)}`, { headers: ghHeaders });
      if (readResponse.ok) {
        existing = await readResponse.json();
      } else if (readResponse.status !== 404) {
        const detail = await githubError(readResponse);
        return json({ ok: false, error: `GitHub could not read ${path}. Check repository access and Contents read/write permission. ${detail}` }, 502, cors);
      }

      const putBody = {
        message: 'Bharat Itihasa: publish Admin updates',
        content: utf8ToBase64(content),
        branch
      };
      if (existing && existing.sha) putBody.sha = existing.sha;
      const putResponse = await fetch(api, { method: 'PUT', headers: ghHeaders, body: JSON.stringify(putBody) });
      const result = await putResponse.json().catch(() => ({}));
      if (!putResponse.ok) {
        let message = result && result.message ? result.message : `GitHub API returned HTTP ${putResponse.status}.`;
        if (putResponse.status === 401 || putResponse.status === 403) message += ' Make sure GH_TOKEN is a fine-grained token with access to this repository and Contents: Read and write.';
        if (putResponse.status === 409 || putResponse.status === 422) message += ' Another commit may have changed this file. Retry the publish once the latest deployment settles.';
        return json({ ok: false, error: message }, 502, cors);
      }
      return json({ ok: true, message: 'Committed data/overrides.js to GitHub.', commitUrl: result.commit && result.commit.html_url ? result.commit.html_url : '', commitSha: result.commit && result.commit.sha ? result.commit.sha : '' }, 200, cors, { 'Cache-Control': 'no-store' });
    }

    return json({ ok: false, error: 'Not found.' }, 404, cors);
  }
};

function corsHeaders(origin, allowedOrigin) {
  if (!origin || origin !== allowedOrigin) return {};
  return {
    'Access-Control-Allow-Origin': allowedOrigin,
    'Vary': 'Origin',
    'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
    'Access-Control-Allow-Headers': 'Authorization, Content-Type',
    'Content-Type': 'application/json; charset=utf-8'
  };
}

function json(data, status = 200, cors = {}, extraHeaders = {}) {
  return new Response(JSON.stringify(data), { status, headers: { ...cors, ...extraHeaders, 'Content-Type': 'application/json; charset=utf-8', 'X-Content-Type-Options': 'nosniff' } });
}

async function readJson(request, limit) {
  const len = Number(request.headers.get('Content-Length') || 0);
  if (len > limit) return { ok: false, status: 413, error: 'Request is too large. Use repository image paths instead of embedding many uploaded images.' };
  const text = await request.text();
  if (new TextEncoder().encode(text).byteLength > limit) return { ok: false, status: 413, error: 'Request is too large. Use repository image paths instead of embedding many uploaded images.' };
  try { return { ok: true, data: JSON.parse(text) }; }
  catch { return { ok: false, status: 400, error: 'Request body must be valid JSON.' }; }
}

async function signSession(claims, secret) {
  const data = base64UrlEncode(new TextEncoder().encode(JSON.stringify(claims)));
  const signature = await hmac(data, secret);
  return `${data}.${base64UrlEncode(signature)}`;
}

async function verifySession(header, secret) {
  if (!secret || !header.startsWith('Bearer ')) return null;
  const token = header.slice(7).trim();
  const pieces = token.split('.');
  if (pieces.length !== 2) return null;
  const expected = base64UrlEncode(await hmac(pieces[0], secret));
  if (!constantTimeStringEqual(pieces[1], expected)) return null;
  try {
    const claims = JSON.parse(new TextDecoder().decode(base64UrlDecode(pieces[0])));
    if (claims.sub !== 'bharat-itihasa-admin' || !Number.isFinite(claims.exp) || claims.exp <= Date.now()) return null;
    return claims;
  } catch { return null; }
}

async function hmac(value, secret) {
  const key = await crypto.subtle.importKey('raw', new TextEncoder().encode(secret), { name: 'HMAC', hash: 'SHA-256' }, false, ['sign']);
  return new Uint8Array(await crypto.subtle.sign('HMAC', key, new TextEncoder().encode(value)));
}

function base64UrlEncode(bytes) {
  let binary = '';
  for (let i = 0; i < bytes.length; i++) binary += String.fromCharCode(bytes[i]);
  return btoa(binary).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/g, '');
}
function base64UrlDecode(text) {
  const padded = text.replace(/-/g, '+').replace(/_/g, '/') + '='.repeat((4 - text.length % 4) % 4);
  const binary = atob(padded);
  return Uint8Array.from(binary, c => c.charCodeAt(0));
}
function base64ToUtf8(text) {
  const clean = String(text || '').replace(/\s/g, '');
  const binary = atob(clean);
  const bytes = Uint8Array.from(binary, c => c.charCodeAt(0));
  return new TextDecoder().decode(bytes);
}
function utf8ToBase64(text) {
  const bytes = new TextEncoder().encode(text);
  return base64UrlEncodeStandard(bytes);
}
function base64UrlEncodeStandard(bytes) {
  let binary = '';
  const chunkSize = 0x8000;
  for (let i = 0; i < bytes.length; i += chunkSize) binary += String.fromCharCode(...bytes.subarray(i, i + chunkSize));
  return btoa(binary);
}
function randomToken(size) {
  const bytes = crypto.getRandomValues(new Uint8Array(size));
  return base64UrlEncode(bytes);
}
function constantTimeStringEqual(a, b) {
  if (typeof a !== 'string' || typeof b !== 'string') return false;
  let diff = a.length ^ b.length;
  const length = Math.max(a.length, b.length);
  for (let i = 0; i < length; i++) diff |= (a.charCodeAt(i) || 0) ^ (b.charCodeAt(i) || 0);
  return diff === 0;
}
async function githubError(response) {
  try { const data = await response.json(); return data && data.message ? `GitHub says: ${data.message}` : `GitHub API HTTP ${response.status}.`; }
  catch { return `GitHub API HTTP ${response.status}.`; }
}
